def pil_to_base64(img):
    buffer = BytesIO()
    img.save(buffer, format="PNG")
    return base64.b64encode(buffer.getvalue()).decode()


def test_intent(user_input: str):
    img_scene = Image.open(os.path.join(DATA_DIR, "original_rgb.png"))
    prompt = INTENT_UNDERSTANDING_PROMPT.format(user_input=user_input)

    response = client.chat.completions.create(
        model="gpt-4o",
        messages=[{
            "role": "user",
            "content": [
                {"type": "text", "text": prompt},
                {"type": "image_url", "image_url": {"url": f"data:image/png;base64,{pil_to_base64(img_scene)}"}},
            ]
        }]
    )

    raw = response.choices[0].message.content
    print("=== 原始回應 ===")
    print(raw)
    try:
        result = json.loads(raw.replace("```json", "").replace("```", "").strip())
        print("\n=== 解析結果 ===")
        print(f"物件名稱：{result['object_name']}")
        print(f"信心程度：{result['confidence']}")
        print(f"推理說明：{result['reasoning']}")
    except json.JSONDecodeError as e:
        print(f"\n⚠️ JSON 解析失敗：{e}")


if __name__ == "__main__":
    user_input = input("請輸入你想要的物件描述：").strip()
    test_intent(user_input)
